// goFiles classifies like the Go extractor: a .go file makes its directory
// a package and a _test.go file is a test.
type goFiles struct{}

func (goFiles) ClassifyFile(rel string) metrics.SourceFile {
	if !strings.HasSuffix(rel, ".go") {
		return metrics.SourceFile{}
	}
	return metrics.SourceFile{Kind: metrics.PackageSource, Package: path.Dir(rel), Test: strings.HasSuffix(rel, "_test.go")}
}

func (goFiles) IsModuleMarker(name string) bool { return name == "go.mod" }

// repo is a test repository: git runs in dir with a fixed identity.
type repo struct {
	t   *testing.T
	dir string
}

func newRepo(t *testing.T) *repo {
	t.Helper()
	r := &repo{t: t, dir: t.TempDir()}
	r.git("init", "-q", "-b", "master")
	return r
}

func (r *repo) git(args ...string) {
	r.t.Helper()
	cmd := exec.Command("git", args...)
	cmd.Dir = r.dir
	env := []string{"GIT_CONFIG_GLOBAL=" + os.DevNull, "GIT_CONFIG_NOSYSTEM=1",
		"GIT_COMMITTER_NAME=t", "GIT_COMMITTER_EMAIL=t@example.com"}
	for _, kv := range os.Environ() {
		if !strings.HasPrefix(kv, "GIT_") {
			env = append(env, kv)
		}
	}
	cmd.Env = env
	if out, err := cmd.CombinedOutput(); err != nil {
		r.t.Fatalf("git %s: %v\n%s", strings.Join(args, " "), err, out)
	}
}

// commit writes files, keyed by slash path, removes those whose body is
// "-", and commits everything as author.
func (r *repo) commit(author string, files map[string]string) {
	r.t.Helper()
	for name, body := range files {
		p := filepath.Join(r.dir, filepath.FromSlash(name))
		if body == "-" {
			if err := os.Remove(p); err != nil {
				r.t.Fatal(err)
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			r.t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o600); err != nil {
			r.t.Fatal(err)
		}
	}
	r.git("add", "-A")
	r.git("commit", "-q", "--no-verify", "--allow-empty", "--author", author+" <"+author+">", "-m", "change")
}

// generated reports the files whose text starts with a generated header.
func generated(p string) bool {
	b, err := os.ReadFile(p)
	return err == nil && strings.HasPrefix(string(b), "// Code generated by x. DO NOT EDIT.")
}

func TestMeasure(t *testing.T) {
	if testing.Short() {
		t.Skip("integration test: runs git")
	}
	t.Parallel()

	r := newRepo(t)
	r.commit("a@example.com", map[string]string{"go.mod": "module m\n", "a/a.go": "package a\n", "b/b.go": "package b\n"})
	// A test file, a generated file and a file outside every package
	// count for nothing.
	r.commit("b@example.com", map[string]string{"a/a_test.go": "package a\n", "README": "x\n",
		"g/g.go": "// Code generated by x. DO NOT EDIT.\n\npackage g\n"})
	// A side branch merged into master counts once, as the merge,
	// under the merge's author.
	r.git("checkout", "-q", "-b", "side")
	r.commit("c@example.com", map[string]string{"b/b.go": "package b\n\nvar X = 1\n"})
	r.commit("c@example.com", map[string]string{"b/c.go": "package b\n"})
	r.git("checkout", "-q", "master")
	r.git("-c", "user.name=m", "-c", "user.email=M@Example.com", "merge", "-q", "--no-ff", "-m", "merge", "side")
	// A move counts for the package it left and the one it entered.
	r.git("mv", "b/c.go", "a/c.go")
	r.commit("a@example.com", nil)

	tests := []struct {
		name   string
		window int
		want   map[string]Counts
	}{
		{name: "whole history", window: 200, want: map[string]Counts{
			"a": {Commits: 2, Authors: 1}, "b": {Commits: 3, Authors: 2}, "g": {}, ".": {},
		}},
		{name: "last two", window: 2, want: map[string]Counts{
			"a": {Commits: 1, Authors: 1}, "b": {Commits: 2, Authors: 2},
		}},
		{name: "last one", window: 1, want: map[string]Counts{
			"a": {Commits: 1, Authors: 1}, "b": {Commits: 1, Authors: 1},
		}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			ix, err := Measure(t.Context(), r.dir, Options{Window: tt.window, Classifier: goFiles{}, Generated: generated})
			if err != nil {
				t.Fatal(err)
			}
			for dir, want := range tt.want {
				if got := ix.Of(dir); got != want {
					t.Errorf("Of(%q) = %+v, want %+v", dir, got, want)
				}
			}
		})
	}
}

// TestMeasureNestedModule checks that a module below the repository root
// reads paths relative to itself and never counts files outside it.
func TestMeasureNestedModule(t *testing.T) {
	if testing.Short() {
		t.Skip("integration test: runs git")
	}
	t.Parallel()

	r := newRepo(t)
	r.commit("a@example.com", map[string]string{"svc/go.mod": "module m\n", "svc/a/a.go": "package a\n", "a/a.go": "package a\n"})
	r.commit("a@example.com", map[string]string{"a/a.go": "package a\n\nvar X = 1\n"})
	ix, err := Measure(t.Context(), filepath.Join(r.dir, "svc"), Options{Window: 10, Classifier: goFiles{}})
	if err != nil {
		t.Fatal(err)
	}
	if got, want := ix.Of("a"), (Counts{Commits: 1, Authors: 1}); got != want {
		t.Errorf("Of(a) = %+v, want %+v", got, want)
	}
}

func TestMeasureUnavailable(t *testing.T) {
	if testing.Short() {
		t.Skip("integration test: runs git")
	}
	t.Parallel()

	empty := newRepo(t)
	// A repository whose HEAD is listed in .git/shallow reads as a shallow
	// clone, as one fetched with --depth 1 does.
	shallow := newRepo(t)
	shallow.commit("a@example.com", map[string]string{"go.mod": "module m\n", "a/a.go": "package a\n"})
	head, err := exec.Command("git", "-C", shallow.dir, "rev-parse", "HEAD").Output()
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(shallow.dir, ".git", "shallow"), head, 0o600); err != nil {
		t.Fatal(err)
	}
	tests := []struct {
		name   string
		dir    string
		window int
	}{
		{name: "not a repository", dir: t.TempDir(), window: 10},
		{name: "no commit yet", dir: empty.dir, window: 10},
		{name: "window off", dir: empty.dir, window: 0},
		{name: "shallow clone", dir: shallow.dir, window: 10},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			_, err := Measure(t.Context(), tt.dir, Options{Window: tt.window, Classifier: goFiles{}})
			if !errors.Is(err, ErrUnavailable) {
				t.Fatalf("Measure error = %v, want ErrUnavailable", err)
			}
		})
	}
}
