package inspect

import "testing"

func TestIsGenerated(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name string
		src  string
		want bool
	}{
		{"at generated line comment", "// @generated\nexport const a = 1;\n", true},
		{"at generated with detail", "/**\n * @generated SignedSource<<abc>>\n */\nexport const a = 1;\n", true},
		{"go form", "// Code generated by protoc-gen-ts_proto. DO NOT EDIT.\nexport const a = 1;\n", true},
		{"two lines block", "/* This file was automatically generated by a tool.\n * Do not edit it by hand. */\nexport const a = 1;\n", true},
		{"two line comments", "// Generated by graphql-codegen\n// DO NOT MODIFY\nexport const a = 1;\n", true},
		{"mixed case", "// GENERATED FILE - do NOT Edit\nexport const a = 1;\n", true},
		{"after a blank line and a license", "/* MIT */\n\n// @generated\nexport const a = 1;\n", true},
		{"shebang first", "#!/usr/bin/env node\n// @generated\nexport const a = 1;\n", true},
		{"byte order mark first", "\xEF\xBB\xBF// @generated\nexport const a = 1;\n", true},
		{"unterminated block", "/* @generated", true},
		{"marker after the first code token", "export const a = 1;\n// @generated\n", false},
		{"marker after an import", "import x from \"y\";\n// Code generated DO NOT EDIT\n", false},
		{"marker after a directive prologue", "\"use strict\";\n// @generated\n", false},
		{"eslint-disable alone", "/* eslint-disable */\nexport const a = 1;\n", false},
		{"eslint-disable and a prettier note", "/* eslint-disable */\n// prettier-ignore\nexport const a = 1;\n", false},
		{"generated without do not edit", "// This module is generated at build time.\nexport const a = 1;\n", false},
		{"do not edit without generated", "// Do not edit.\nexport const a = 1;\n", false},
		{"shebang only", "#!/usr/bin/env node", false},
		{"empty", "", false},
		{"generates is not generated", "// This generates reports. Do not edit.\n", false},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			if got := IsGenerated([]byte(tt.src)); got != tt.want {
				t.Errorf("IsGenerated(%q) = %v, want %v", tt.src, got, tt.want)
			}
		})
	}
}
