// TestGeneratedRoles checks SPEC.md 6.5: a package all of whose non-test
// files are generated is generated-only, though it exports nothing as far
// as the count goes; one hand-written file makes it a library; a package
// a bin entry names stays main; and an eslint-disable header alone marks
// nothing.
func TestGeneratedRoles(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, map[string]string{
		"package.json":       `{"bin": {"tool": "./cli/index.ts"}}`,
		"gen/a.ts":           "// @generated\nexport const a = 1;\n",
		"gen/b.ts":           "/* Code generated by a tool. DO NOT EDIT. */\nexport const b = 2;\n",
		"mixed/gen.ts":       "// @generated\nexport const g = 1;\n",
		"mixed/hand.ts":      "export const h = 1;\n",
		"eslint/lint.ts":     "/* eslint-disable */\nexport const l = 1;\n",
		"cli/index.ts":       "// @generated\nexport const version = 1;\n",
		"barrel/index.ts":    "// @generated\nexport * from \"../gen/a\";\nexport { b } from \"../gen/b\";\n",
		"barrel/gen.test.ts": "// @generated\nimport { it } from \"vitest\";\nit(\"x\", () => {});\n",
	})
	e := New()
	mod := &metrics.ModuleContext{Root: root}
	for pkg, want := range map[string]string{
		"gen":    role.GeneratedOnly,
		"barrel": role.GeneratedOnly,
		"mixed":  role.Library,
		"eslint": role.Library,
		"cli":    role.Main,
	} {
		m, err := e.Extract(t.Context(), mod, pkg)
		if err != nil {
			t.Fatalf("Extract(%s): %v", pkg, err)
		}
		if m.Role != want {
			t.Errorf("%s role = %q, want %q", pkg, m.Role, want)
		}
	}
}

// TestGeneratedMetrics checks a package of one generated and one
// hand-written file: the generated file counts in files, generated_files,
// tokens_est_generated and the imports, and in no other metric.
func TestGeneratedMetrics(t *testing.T) {
	const gen = "// @generated\nimport { z } from \"zod\";\nimport * as fs from \"node:fs\";\nimport { other } from \"../other\";\n" +
		"export let cache = 0;\nexport function parse(s: string): string {\n  if (s) {\n    return z.string().parse(s) + fs.name + other;\n  }\n  return \"\";\n}\n" +
		"export { x } from \"../other\";\n"
	const hand = "export function hand(): number {\n  return 1;\n}\n"
	root := t.TempDir()
	writeTree(t, root, map[string]string{
		"pkg/gen.ts":     gen,
		"pkg/hand.ts":    hand,
		"other/index.ts": "export const other = \"o\";\nexport const x = 1;\n",
	})
	e := New()
	mod := &metrics.ModuleContext{Root: root}
	m, err := e.Extract(t.Context(), mod, "pkg")
	if err != nil {
		t.Fatalf("Extract: %v", err)
	}
	if m.Files != 2 || *m.GeneratedFiles != 1 {
		t.Errorf("files = %d, generated_files = %d, want 2 and 1", m.Files, *m.GeneratedFiles)
	}
	if want := 87; *m.TokensEstGenerated != want {
		t.Errorf("tokens_est_generated = %d, want %d", *m.TokensEstGenerated, want)
	}
	if want := 14; m.TokensEst != want || m.TokensEstWithTests != want {
		t.Errorf("tokens_est = %d, with tests %d, want %d", m.TokensEst, m.TokensEstWithTests, want)
	}
	if m.SLOC != 3 || m.LargestFileSLOC != 3 {
		t.Errorf("sloc = %d, largest = %d, want 3 and 3", m.SLOC, m.LargestFileSLOC)
	}
	if m.InternalImports != 1 || m.ExternalImports != 1 || m.StdlibImports != 1 {
		t.Errorf("imports = %d internal, %d external, %d stdlib, want 1, 1, 1", m.InternalImports, m.ExternalImports, m.StdlibImports)
	}
	if m.ExportedSymbols != 1 || m.Globals != 0 || m.FuncCount != 1 || m.CyclomaticTotal != 1 || m.UntestedExports != 1 {
		t.Errorf("exported_symbols = %d, globals = %d, func_count = %d, cyclomatic_total = %d, untested_exports = %d, want 1, 0, 1, 1, 1",
			m.ExportedSymbols, m.Globals, m.FuncCount, m.CyclomaticTotal, m.UntestedExports)
	}
	other, err := e.Extract(t.Context(), mod, "other")
	if err != nil {
		t.Fatalf("Extract(other): %v", err)
	}
	if other.FanIn != 1 {
		t.Errorf("other fan_in = %d, want 1: a generated file's imports still count", other.FanIn)
	}
	fns, err := e.Functions(t.Context(), mod, "pkg")
	if err != nil {
		t.Fatalf("Functions: %v", err)
	}
	if len(fns) != 1 || fns[0].Name != "hand" {
		t.Errorf("functions = %+v, want only hand", fns)
	}
}

func TestIsGeneratedFile(t *testing.T) {
	dir := t.TempDir()
	writeTree(t, dir, map[string]string{
		"gen.ts":  "// @generated\nexport const a = 1;\n",
		"hand.ts": "/* eslint-disable */\nexport const a = 1;\n",
	})
	for name, want := range map[string]bool{"gen.ts": true, "hand.ts": false, "gone.ts": false} {
		if got := IsGeneratedFile(filepath.Join(dir, name)); got != want {
			t.Errorf("IsGeneratedFile(%s) = %v, want %v", name, got, want)
		}
	}
}
