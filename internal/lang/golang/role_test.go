package golang

import (
	"maps"
	"os"
	"path/filepath"
	"testing"

	"github.com/rfizzle/astimate/internal/metrics"
	"github.com/rfizzle/astimate/internal/metrics/role"
)

// flagTable is a declarative block, a composite literal long enough to be
// a cross-package duplicate, that two commands of the roles module share.
const flagTable = `
var flags = []struct {
	name, usage string
	def         int
}{
	{"alpha", "the first flag of the command", 1},
	{"beta", "the second flag of the command", 2},
	{"gamma", "the third flag of the command", 3},
	{"delta", "the fourth flag of the command", 4},
	{"epsilon", "the fifth flag of the command", 5},
}
`

// TestRoles checks SPEC.md 6.5: a package main is main, one whose every
// non-test file is generated is generated-only, one only other packages'
// tests use is test-support, and any other is a library; the module
// details give the role of every package a cross-package block lies in.
func TestRoles(t *testing.T) {
	dir := t.TempDir()
	files := map[string]string{
		"go.mod":              "module example.com/roles\n\ngo 1.27\n",
		"cmd/a/main.go":       "package main\n" + flagTable + "\nfunc main() { _ = flags }\n",
		"cmd/b/main.go":       "package main\n" + flagTable + "\nfunc main() {\n\tfor range flags {\n\t}\n}\n",
		"lib/lib.go":          "// Package lib is a library.\npackage lib\n\n// Double doubles n.\nfunc Double(n int) int { return 2 * n }\n",
		"lib/lib_test.go":     "package lib\n\nimport (\n\t\"testing\"\n\n\t\"example.com/roles/fake\"\n)\n\nfunc TestDouble(t *testing.T) {\n\tif Double(fake.One()) != 2 {\n\t\tt.Fatal()\n\t}\n}\n",
		"fake/fake.go":        "// Package fake helps tests.\npackage fake\n\n// One returns 1.\nfunc One() int { return 1 }\n",
		"gen/zz_generated.go": "// Code generated by a test. DO NOT EDIT.\n\npackage gen\n\n// V is generated.\nconst V = 1\n",
	}
	for rel, data := range files {
		p := filepath.Join(dir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		writeFile(t, p, data)
	}
	e := New()
	mod := &metrics.ModuleContext{Root: dir}
	want := map[string]string{
		"example.com/roles/cmd/a": role.Main,
		"example.com/roles/cmd/b": role.Main,
		"example.com/roles/lib":   role.Library,
		"example.com/roles/fake":  role.TestSupport,
		"example.com/roles/gen":   role.GeneratedOnly,
	}
	for pkg, w := range want {
		m, err := e.Extract(t.Context(), mod, pkg)
		if err != nil {
			t.Fatalf("Extract(%s): %v", pkg, err)
		}
		if m.Role != w {
			t.Errorf("%s role = %q, want %q", pkg, m.Role, w)
		}
	}
	det, err := e.ModuleDetails(t.Context(), mod)
	if err != nil {
		t.Fatalf("ModuleDetails: %v", err)
	}
	if len(det.CrossBlocks) == 0 || det.CrossBlocks[0].Kind != "declarative" {
		t.Fatalf("cross blocks = %+v, want the shared flag table, declarative", det.CrossBlocks)
	}
	if wantRoles := map[string]string{"example.com/roles/cmd/a": role.Main, "example.com/roles/cmd/b": role.Main}; !maps.Equal(det.Roles, wantRoles) {
		t.Errorf("module details roles = %v, want %v", det.Roles, wantRoles)
	}
}
